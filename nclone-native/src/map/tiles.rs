/// verbatim from `docs/decomp/TILE_TABLES_2.txt` §C, as `(horizontal, vertical)`.
///
/// **Ternary, and that is the point.** `0` no edge, `1` a PARTIAL face (a slope
/// or a curve), `2` a full flat face. [`TILE_GRID_EDGE_MAP`] collapses 1 and 2
